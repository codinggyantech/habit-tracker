"""Builds the importable 60-day plan from tools/plan_content.py (the same content as 60_Day_Master_Plan.xlsx).

Writes:  plans/60-day-master-plan.json   (import in the app: Boards > Import plan)
         plans/60-day-master-plan.csv    (same tasks as a spreadsheet you can edit in Excel / Google Sheets)
         plans/builtin-plan.js           (lets the app offer a one-click "Load the 60-day plan" button, also when opened as a file)
Run:     python3 tools/make_plan_files.py
"""
import csv, json, pathlib
from plan_content import HEALTH, WORK, WEALTH, SELF, MINUTES

root = pathlib.Path(__file__).resolve().parent.parent
out = root / "plans"
out.mkdir(exist_ok=True)

BOARDS = [  # key, name, icon, colour, linked habit category, minutes key, tasks
    ("health", "Health", "💪", "#16a34a", "health", "Health", HEALTH),
    ("work", "Work & Skills", "🚀", "#0284c7", "learning", "Work", WORK),
    ("wealth", "Wealth", "💰", "#ca8a04", "wealth", "Wealth", WEALTH),
    ("self", "Self & Mind", "🧘", "#9333ea", "mind", "Self", SELF),
]

def day_kind(i):                 # Day 1 is a Sunday. 0 = weekday, 1 = Saturday, 2 = Sunday
    d = i % 7
    return 2 if d == 0 else 1 if d == 6 else 0

boards = []
for key, name, icon, colour, cat, mkey, weeks in BOARDS:
    tasks = []
    flat = [t for w in weeks for t in w]
    assert len(flat) == 60, (name, len(flat))
    for i, title in enumerate(flat):
        kind = day_kind(i)
        tasks.append({"day": i + 1, "title": title, "minutes": MINUTES[mkey][kind], "priority": "high" if kind == 1 else "medium"})
    boards.append({"key": key, "name": name, "icon": icon, "color": colour, "category": cat, "tasks": tasks})

# starter habits that belong to each area (they appear under Goals and on each board's "Related habits" strip)
HABITS = [
    {"name": "Daily movement (30+ min)", "type": "daily", "category": "health", "priority": "high", "icon": "🏃"},
    {"name": "500 push-ups", "type": "total", "target": 500, "unit": "push-ups", "step": 20, "category": "health", "priority": "high", "icon": "💪"},
    {"name": "Workouts", "type": "times", "target": 24, "category": "health", "priority": "medium", "icon": "🏋️"},
    {"name": "Learning sessions", "type": "times", "target": 40, "category": "learning", "priority": "high", "icon": "📚"},
    {"name": "Code or build something", "type": "daily", "category": "learning", "priority": "medium", "icon": "⚡"},
    {"name": "Track spending", "type": "daily", "category": "wealth", "priority": "medium", "icon": "💰"},
    {"name": "Side-income actions", "type": "times", "target": 30, "category": "wealth", "priority": "medium", "icon": "🎯"},
    {"name": "Journal + 3 gratitudes", "type": "daily", "category": "mind", "priority": "medium", "icon": "✍️"},
    {"name": "Read 20 minutes", "type": "daily", "category": "mind", "priority": "low", "icon": "📖"},
    {"name": "Meditate 10 minutes", "type": "times", "target": 40, "category": "mind", "priority": "low", "icon": "🧘"},
]
for h in HABITS:
    h.setdefault("days", 60)

plan = {"app": "habit-tracker", "type": "plan", "schemaVersion": 1, "name": "60-Day Master Plan",
        "description": "240 tasks across Health, Work & Skills, Wealth and Self, sized for a Mon-Fri 9-7 job. Day 1 is a Sunday.",
        "startDate": "2026-11-01", "boards": boards, "habits": HABITS}

(out / "60-day-master-plan.json").write_text(json.dumps(plan, ensure_ascii=False, indent=2), encoding="utf-8")
with open(out / "60-day-master-plan.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f)
    w.writerow(["board", "day", "due", "title", "minutes", "priority", "notes"])
    for b in boards:
        for t in b["tasks"]:
            w.writerow([b["name"], t["day"], "", t["title"], t["minutes"], t["priority"], ""])
(out / "builtin-plan.js").write_text("// generated by tools/make_plan_files.py - do not edit by hand\nwindow.BUILTIN_PLAN = " + json.dumps(plan, ensure_ascii=False) + ";\n", encoding="utf-8")
print("wrote", sum(len(b["tasks"]) for b in boards), "tasks,", len(HABITS), "habits")
